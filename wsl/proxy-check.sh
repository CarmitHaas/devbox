#!/usr/bin/env bash
# proxy-check.sh: can this WSL distro reach the hosts the toolchain needs, and does
# the TLS chain validate? One line per host: PASS, CA-MISSING, BLOCKED, DNS-FAIL, ...
#
# Usage:
#   proxy-check.sh [--ca FILE] [--timeout SEC] [extra-host ...]
#
#   --ca FILE      validate against this CA bundle instead of the system store
#   --timeout SEC  per-host connect timeout (default 5)
#   extra-host     additional hostnames to test
#
# Exit code 0 when every host passes, 1 otherwise. No sudo needed.
#
# Reading the result:
#   PASS         TLS validated and the host answered (any HTTP code counts; 403 from S3/CDN is normal)
#   CA-MISSING   TLS failed with the system CA but works insecurely: the proxy re-signs
#                traffic and its CA is not trusted here. Run install-corp-ca.sh.
#   BLOCKED      connection refused, reset, timed out, or TLS handshake killed: the proxy
#                or a firewall denies this host. Ask IT to allow it.
#   PROXY-AUTH   HTTP 407: an explicit proxy wants credentials (set HTTPS_PROXY with user:pass)
#   PASS + 403   the host answered with a valid chain. Could be a proxy block page; check in a browser.
#   DNS-FAIL     name resolution failed: see the DNS section in README.md

set -euo pipefail

CA_FILE=""
TIMEOUT=5
EXTRA=()

while [ $# -gt 0 ]; do
  case "$1" in
    -h|--help) sed -n '2,/^$/p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    --ca) CA_FILE="${2:?--ca needs a file}"; shift 2 ;;
    --timeout) TIMEOUT="${2:?--timeout needs seconds}"; shift 2 ;;
    -*) echo "unknown option: $1" >&2; exit 2 ;;
    *) EXTRA+=("$1"); shift ;;
  esac
done

command -v curl >/dev/null 2>&1 || { echo "curl is required (sudo apt-get install -y curl)" >&2; exit 2; }

# host:path pairs; path chosen so a reachable host answers something
HOSTS=(
  "github.com:/"
  "api.github.com:/"
  "raw.githubusercontent.com:/"
  "objects.githubusercontent.com:/"
  "copilot-proxy.githubusercontent.com:/"
  "cli.github.com:/packages/"
  "registry.npmjs.org:/"
  "pypi.org:/"
  "files.pythonhosted.org:/"
  "astral.sh:/"
  "archive.ubuntu.com:/ubuntu/"
  "security.ubuntu.com:/ubuntu/"
  "registry-1.docker.io:/v2/"
  "auth.docker.io:/"
  "ghcr.io:/v2/"
  "releases.hashicorp.com:/"
  "apt.releases.hashicorp.com:/"
  "pkgs.k8s.io:/"
  "dl.k8s.io:/release/stable.txt"
  "get.helm.sh:/helm-latest-version"
  "awscli.amazonaws.com:/"
  "starship.rs:/"
  "claude.ai:/"
  "api.anthropic.com:/"
  "marketplace.visualstudio.com:/"
  "update.code.visualstudio.com:/"
)
for h in "${EXTRA[@]+"${EXTRA[@]}"}"; do HOSTS+=("$h:/"); done

bold()  { printf '\033[1m%s\033[0m\n' "$*"; }
mask()  { sed -E 's#(://)[^/@]+@#\1***@#g'; }

# --- environment -----------------------------------------------------------

bold "Proxy environment"
found=0
for v in http_proxy https_proxy no_proxy HTTP_PROXY HTTPS_PROXY NO_PROXY ALL_PROXY; do
  if [ -n "${!v:-}" ]; then
    printf '  %-12s %s\n' "$v" "$(printf '%s' "${!v}" | mask)"
    found=1
  fi
done
[ "$found" -eq 1 ] || echo "  none set (fine for a transparent proxy; an explicit proxy needs HTTPS_PROXY)"
if [ -f /etc/apt/apt.conf.d/95-devbox-proxy ] || grep -rqs 'Acquire::http.*Proxy' /etc/apt/apt.conf.d/ 2>/dev/null; then
  echo "  apt proxy config present in /etc/apt/apt.conf.d/"
fi

bold "DNS"
if [ -r /etc/resolv.conf ]; then
  if grep -q 'automatically generated by WSL' /etc/resolv.conf; then
    echo "  /etc/resolv.conf is generated by WSL (generateResolvConf=true)"
  else
    echo "  /etc/resolv.conf is static (generateResolvConf=false or hand edited)"
  fi
  grep -E '^(nameserver|search)' /etc/resolv.conf | sed 's/^/  /'
else
  echo "  /etc/resolv.conf missing"
fi
PWSH="/mnt/c/Windows/System32/WindowsPowerShell/v1.0/powershell.exe"
if [ -x "$PWSH" ]; then
  # shellcheck disable=SC2016
  windns=$(cd /mnt/c 2>/dev/null && timeout 15 "$PWSH" -NoProfile -NonInteractive -Command \
    'Get-DnsClientServerAddress -AddressFamily IPv4 | Where-Object { $_.ServerAddresses } | ForEach-Object { $_.InterfaceAlias + ": " + ($_.ServerAddresses -join ", ") }' 2>/dev/null | tr -d '\r') || true
  if [ -n "$windns" ]; then
    echo "  Windows DNS servers (what WSL should use when on VPN):"
    printf '%s\n' "$windns" | sed 's/^/    /'
  fi
fi

# --- reachability ----------------------------------------------------------

bold "Reachability (timeout ${TIMEOUT}s per host)"
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

CURL_CA=()
[ -n "$CA_FILE" ] && CURL_CA=(--cacert "$CA_FILE")

issuer_of() {
  # who signed the certificate we are actually shown (through an explicit proxy if set)
  local host=$1 proxy_opt=()
  local p="${https_proxy:-${HTTPS_PROXY:-}}"
  if [ -n "$p" ]; then
    p="${p#*://}"; p="${p%%/*}"; p="${p##*@}"
    proxy_opt=(-proxy "$p")
  fi
  command -v openssl >/dev/null 2>&1 || return 0
  echo | timeout "$((TIMEOUT + 3))" openssl s_client -connect "$host:443" -servername "$host" "${proxy_opt[@]+"${proxy_opt[@]}"}" 2>/dev/null \
    | openssl x509 -noout -issuer 2>/dev/null | sed 's/^issuer=//' || true
}

check_one() {
  local host=$1 path=$2 out=$3 code rc status detail=""
  code=$(curl -sS -o /dev/null -w '%{http_code}' --connect-timeout "$TIMEOUT" --max-time "$((TIMEOUT * 2))" \
           "${CURL_CA[@]+"${CURL_CA[@]}"}" "https://$host$path" 2>"$out.err") && rc=0 || rc=$?
  case "$rc" in
    0)
      status="PASS"
      case "$code" in
        407) status="PROXY-AUTH" ;;
        403) detail="403 after a valid TLS handshake: S3/CDN default, bot protection, or a proxy block page. Open it in a browser to tell." ;;
      esac
      ;;
    60|77)
      # try again without verification to tell CA-MISSING apart from BLOCKED
      if curl -sk -o /dev/null --connect-timeout "$TIMEOUT" --max-time "$((TIMEOUT * 2))" "https://$host$path" 2>/dev/null; then
        status="CA-MISSING"; detail="issuer: $(issuer_of "$host")"
      else
        status="BLOCKED"; detail="tls error then no insecure connection either"
      fi
      code="-"
      ;;
    6)  status="DNS-FAIL"; code="-" ;;
    5)  status="PROXY-DNS-FAIL"; code="-"; detail="cannot resolve the proxy host" ;;
    7)  status="BLOCKED"; code="-"; detail="connection refused/unreachable" ;;
    28) status="BLOCKED"; code="-"; detail="timed out" ;;
    35) status="BLOCKED"; code="-"; detail="TLS handshake killed: $(head -c 80 "$out.err" | tr -d '\n')" ;;
    52) status="BLOCKED"; code="-"; detail="empty reply" ;;
    56) status="BLOCKED"; code="-"; detail="connection reset" ;;
    *)  status="ERROR"; code="-"; detail="curl exit $rc: $(head -c 80 "$out.err" | tr -d '\n')" ;;
  esac
  printf '%s\t%s\t%s\n' "$status" "$code" "$detail" > "$out"
}

i=0
for entry in "${HOSTS[@]}"; do
  host="${entry%%:*}"; path="${entry#*:}"
  check_one "$host" "$path" "$WORK/$i" &
  i=$((i + 1))
done
wait

printf '  %-40s %-14s %-5s %s\n' "HOST" "STATUS" "HTTP" "DETAIL"
fail=0
i=0
declare -A SEEN_ISSUERS=()
for entry in "${HOSTS[@]}"; do
  host="${entry%%:*}"
  IFS=$'\t' read -r status code detail < "$WORK/$i"
  color='\033[0;32m'
  case "$status" in
    PASS) ;;
    CA-MISSING) color='\033[0;33m'; fail=1; SEEN_ISSUERS["$detail"]=1 ;;
    *) color='\033[0;31m'; fail=1 ;;
  esac
  printf "  %-40s ${color}%-14s\033[0m %-5s %s\n" "$host" "$status" "$code" "$detail"
  i=$((i + 1))
done

echo
if [ "$fail" -eq 0 ]; then
  bold "All hosts reachable with a valid TLS chain."
  exit 0
fi

if [ "${#SEEN_ISSUERS[@]}" -gt 0 ]; then
  bold "Interception detected. Certificates are signed by:"
  for k in "${!SEEN_ISSUERS[@]}"; do echo "  ${k#issuer: }"; done
  echo "  Export that CA with windows/export-corp-ca.ps1 and run wsl/install-corp-ca.sh."
fi
bold "Some hosts failed. BLOCKED hosts go into the IT message (windows/README.md)."
exit 1
